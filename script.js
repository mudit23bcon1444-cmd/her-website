function initDust() {
  const ctx = dustCanvas.getContext('2d');

  function resize() {
    dustCanvas.width  = window.innerWidth;
    dustCanvas.height = window.innerHeight;
  }
  resize();
  window.addEventListener('resize', resize);

  const COUNT = 55;
  const particles = [];
  for (let i = 0; i < COUNT; i++) {
    particles.push({
      x:     Math.random() * window.innerWidth,
      y:     Math.random() * window.innerHeight,
      r:     Math.random() * 1.8 + 0.4,
      vx:    (Math.random() - 0.5) * 0.25,
      vy:    -(Math.random() * 0.5 + 0.1),
      alpha: Math.random() * 0.5 + 0.1,
    });
  }

  function drawDust() {
    if (!scene1.classList.contains('active')) { requestAnimationFrame(drawDust); return; }
    ctx.clearRect(0, 0, dustCanvas.width, dustCanvas.height);
    for (const p of particles) {
      p.x += p.vx; p.y += p.vy;
      if (p.y < -5)                    p.y = dustCanvas.height + 5;
      if (p.x < -5)                    p.x = dustCanvas.width  + 5;
      if (p.x > dustCanvas.width + 5)  p.x = -5;
      ctx.beginPath();
      ctx.arc(p.x, p.y, p.r, 0, Math.PI * 2);
      ctx.fillStyle = `rgba(255,200,180,${p.alpha})`;
      ctx.fill();
    }
    requestAnimationFrame(drawDust);
  }
  requestAnimationFrame(drawDust);
}

