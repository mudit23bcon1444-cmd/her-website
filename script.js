function preloadAssets() {
  const imgPaths   = CONFIG.images;
  const audioPaths = CONFIG.audio;
  const total      = imgPaths.length + audioPaths.length + 1; // +1 for strip PNG
  let   loaded     = 0;

  function tick() {
    loaded++;
    loaderFill.style.width = (loaded / total * 100) + '%';
  }

  const imgPromises = imgPaths.map(src => new Promise(res => {
    const img = new Image();
    img.onload = img.onerror = () => { tick(); res(); };
    img.src = src;
  }));

  const stripPromise = new Promise(res => {
    const img = new Image();
    img.onload = img.onerror = () => { tick(); res(); };
    img.src = CONFIG.cleanStripSrc;
  });

  const audioPromises = audioPaths.map(src => new Promise(res => {
    const a = new Audio();
    a.oncanplaythrough = a.onerror = () => { tick(); res(); };
    a.src = src;
    a.load();
  }));

  return Promise.all([...imgPromises, stripPromise, ...audioPromises]);
}

